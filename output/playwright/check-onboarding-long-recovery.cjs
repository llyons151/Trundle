async (page) => {
  const assert = (ok, message) => { if (!ok) throw Error(message); };
  const button = name => page.getByRole('button', {name,exact:true});
  const root = step => page.getByTestId(`onboarding-${step}`);
  const next = async step => { await root(step).waitFor(); await root(step).locator(':scope > div').nth(4).getByRole('button').click(); };
  const results = [];
  await page.setViewportSize({width:320,height:568});
  await page.evaluate(()=>localStorage.removeItem('trundle.onboarding.v1')); await page.reload();
  await next('welcome');
  await button('Choose later').click();
  await page.getByRole('radio',{name:'First thing in the morning',exact:true}).click();
  await next('habit');
  assert(await page.getByRole('heading',{name:'Start with yourself. The feed can wait.'}).count(), 'Morning answer did not personalize insight');
  await button('Back').click();
  await page.getByRole('radio',{name:'At both ends of the day',exact:true}).click(); await next('habit');
  assert(await page.getByRole('heading',{name:'A quieter ending. A gentler beginning.'}).count(), 'Both answer did not personalize insight');
  await button('Explore first').click(); await button('Continue setting up our routine').waitFor();
  await page.reload(); await button('Continue setting up our routine').click(); await root('insight').waitFor();
  results.push('optional goal, both insight branches, and explore/resume after reload');
  await next('insight'); await next('bedtime');
  await button('Edit bedtime, 10:00 PM').click();
  await page.getByRole('combobox').first().selectOption('7'); await button('Done').click();
  assert(await button('Set our morning').isDisabled(), 'Equal schedule times accepted');
  await button('Edit bedtime, 7:00 AM').click();
  await page.getByRole('combobox').first().selectOption('23'); await button('Done').click();
  await next('schedule');
  await button('Edit morning start, 7:00 AM').click();
  await page.getByRole('combobox').first().selectOption('8'); await button('Done').click();
  await next('morning-time');
  await button('How it works & walking alternatives').click();
  await button('What if walking doesn’t work for me?').click();
  await button('Keep exploring').click();
  await next('morning'); await next('apps'); await next('always'); await next('access');
  await button('Choose later').click(); await root('plan').waitFor();
  assert((await root('plan').innerText()).includes('take a moment for myself'), 'Skipped ritual invented an answer');
  await button('Edit goal').click();
  await page.getByRole('radio',{name:'More time for myself',exact:true}).click();
  await button('Back to my plan').click();
  assert((await root('plan').innerText()).includes('More time for myself'), 'Goal edit missing from plan');
  await button('Edit ritual').click();
  await page.getByRole('radio',{name:'Have a gentle stretch',exact:true}).click();
  await button('Back to my plan').click();
  assert((await root('plan').innerText()).includes('have a gentle stretch'), 'Ritual edit missing from plan');
  await next('plan');
  await page.getByRole('button',{name:/^Edit morning starts\./}).click(); await root('morning-time').waitFor();
  await button('Back to review').click();
  await page.getByRole('button',{name:/^Edit always-blocked apps\./}).click(); await root('always').waitFor();
  await button('Back to review').click();
  results.push('time editing and validation; walking alternatives; plan/review edit return destinations');
  await page.evaluate(()=>{
    window.__setItem = Storage.prototype.setItem;
    window.__failSetup = true;
    Storage.prototype.setItem = function(key,value) {
      if(window.__failSetup && key === 'trundle.onboarding.v1') throw Error('Quota');
      return window.__setItem.call(this,key,value);
    };
  });
  await next('review'); await button('Retry saving').waitFor();
  assert(await root('review').count(), 'Failed completion exited setup');
  await page.evaluate(()=>{window.__failSetup=false;}); await button('Retry saving').click();
  await button('Open your profile').waitFor();
  const saved = await page.evaluate(()=>({prefs:JSON.parse(localStorage.getItem('trundle.preferences.v1')),setup:JSON.parse(localStorage.getItem('trundle.onboarding.v1'))}));
  assert(saved.prefs.bedtime===1380 && saved.prefs.morning===480 && saved.setup.answers.ritual==='stretch', 'Save lost settings/answers');
  assert(!('steps' in saved.prefs),'Simulation leaked into actual step data');
  await button('Open your profile').click(); await button('Replay onboarding').click(); await root('welcome').waitFor();
  assert((await page.evaluate(()=>JSON.parse(localStorage.getItem('trundle.preferences.v1')))).morning===480,'Replay erased preferences');
  await next('welcome');
  await page.evaluate(()=>{window.__failSetup=true;});
  await page.getByRole('radio',{name:'Quieter evenings',exact:true}).click(); await button('Retry saving').waitFor();
  await page.evaluate(()=>{window.__failSetup=false;}); await button('Retry saving').click();
  await page.reload();
  assert(await page.getByRole('radio',{name:'Quieter evenings',exact:true}).getAttribute('aria-checked')==='true','Answer save retry lost selection');
  results.push('failed completion and answer writes recover; developer replay preserves settings');
  return results;
}
